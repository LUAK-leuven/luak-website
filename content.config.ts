import {
  defineCollection,
  defineContentConfig,
  property,
  z,
} from '@nuxt/content';

const hideAutoGeneratedFields = {
  seo: property(z.object({}).optional()).editor({ hidden: true }),
  navigation: property(z.object({}).optional()).editor({ hidden: true }),
  excerpt: property(z.object({}).optional()).editor({ hidden: true }),
  title: property(z.string().optional()).editor({ hidden: true }),
  description: property(z.string().optional()).editor({ hidden: true }),
};

export default defineContentConfig({
  collections: {
    activities: defineCollection({
      type: 'page',
      source: 'activities/*.md',
      schema: z.object({
        ...hideAutoGeneratedFields,
        image: property(z.string()).editor({ input: 'media' }),
        title: z.string().nonempty(),
        date: z.date(),
        price: z.number().int().positive().finite(),
        tag: z.string().optional(),
      }),
    }),
    news: defineCollection({
      type: 'page',
      source: 'news/*.md',
      schema: z.object({
        ...hideAutoGeneratedFields,
        image: property(z.string()).editor({ input: 'media' }),
        title: z.string().nonempty(),
        date: z.date(),
        teaser: z.string().optional(),
      }),
    }),
    pages: defineCollection({
      type: 'page',
      source: 'pages/*.md',
    }),
    infoPages: defineCollection({
      type: 'page',
      source: 'info/*.md',
    }),
    stories: defineCollection({
      type: 'page',
      source: 'stories/*.md',
      schema: z.object({
        ...hideAutoGeneratedFields,
        image: property(z.string()).editor({ input: 'media' }),
        title: z.string().nonempty(),
        date: z.date(),
        author: z.string().nonempty(),
        teaser: z.string().optional(),
      }),
    }),
    shared: defineCollection({
      type: 'data',
      source: 'shared/*.md',
      schema: z.object({}),
    }),
  },
});
